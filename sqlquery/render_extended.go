package sqlquery

import (
	"encoding/base64"
	"encoding/json"
	"fmt"
	"io"
	"strings"
	"unicode"
)

// renderExtended uses standard-library UTF-8/base64 decoders where a target
// language's literal or source-encoding rules cannot preserve arbitrary SQL.
func renderExtended(w io.Writer, lang string, queries []Query, formatted bool) error {
	var b strings.Builder
	p := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }
	q := func(s string) string { v, _ := json.Marshal(s); return string(v) }
	encoded := func(s string) string { return q(base64.StdEncoding.EncodeToString([]byte(s))) }
	jvmEncoded := func(s, language string) string {
		text := base64.StdEncoding.EncodeToString([]byte(s))
		if len(text) <= 16000 {
			return q(text)
		}
		var chunks []string
		for len(text) > 0 {
			n := 16000
			if len(text) < n {
				n = len(text)
			}
			chunks = append(chunks, q(text[:n]))
			text = text[n:]
		}
		switch language {
		case "java":
			return "String.join(\"\", " + strings.Join(chunks, ", ") + ")"
		case "kotlin":
			return "listOf(" + strings.Join(chunks, ", ") + ").joinToString(\"\")"
		default:
			return "Seq(" + strings.Join(chunks, ", ") + ").mkString"
		}
	}
	switch lang {
	case "rust":
		p("// Generated by mmmbed; do not edit.\n#[derive(Debug)]\npub struct Query { pub name: &'static str, pub sql: &'static str, pub access: &'static str, pub rows: &'static str }\npub static QUERIES: &[Query] = &[\n")
		for _, x := range queries {
			p("    Query { name: %s, sql: %s, access: %s, rows: %s },\n", rustString(x.Name), formattedSQLLiteral(lang, x.SQL, formatted, rustString(x.SQL)), rustString(x.Access), rustString(x.Rows))
		}
		p("];\n")
	case "java":
		p("// Generated by mmmbed; do not edit.\nfinal class MmmbedQueries {\n  static final class Query {\n    final String name, sql, access, rows;\n    Query(String name, String sql, String access, String rows) { this.name=name; this.sql=sql; this.access=access; this.rows=rows; }\n  }\n  static final java.util.Map<String, Query> queries;\n  static {\n    java.util.Map<String, Query> items = new java.util.LinkedHashMap<>();\n")
		for _, x := range queries {
			p("    items.put(%s, new Query(%s, %s, %s, %s));\n", q(x.Name), q(x.Name), formattedSQLLiteral(lang, x.SQL, formatted, fmt.Sprintf("new String(java.util.Base64.getDecoder().decode(%s), java.nio.charset.StandardCharsets.UTF_8)", jvmEncoded(x.SQL, "java"))), q(x.Access), q(x.Rows))
		}
		p("    queries = java.util.Collections.unmodifiableMap(items);\n  }\n}\n")
	case "csharp":
		p("// Generated by mmmbed; do not edit.\ninternal static class MmmbedQueries {\n  internal sealed class Query {\n    internal readonly string Name, Sql, Access, Rows;\n    internal Query(string name, string sql, string access, string rows) { Name=name; Sql=sql; Access=access; Rows=rows; }\n  }\n  internal static readonly System.Collections.Generic.IReadOnlyDictionary<string, Query> Queries = new System.Collections.Generic.Dictionary<string, Query> {\n")
		for _, x := range queries {
			p("    { %s, new Query(%s, %s, %s, %s) },\n", q(x.Name), q(x.Name), formattedSQLLiteral(lang, x.SQL, formatted, fmt.Sprintf("System.Text.Encoding.UTF8.GetString(System.Convert.FromBase64String(%s))", encoded(x.SQL))), q(x.Access), q(x.Rows))
		}
		p("  };\n}\n")
	case "php":
		p("<?php\n// Generated by mmmbed; do not edit.\n$queries = [\n")
		for _, x := range queries {
			p("  %s => ['name' => %s, 'sql' => %s, 'access' => %s, 'rows' => %s],\n", q(x.Name), q(x.Name), formattedSQLLiteral(lang, x.SQL, formatted, fmt.Sprintf("base64_decode(%s)", encoded(x.SQL))), q(x.Access), q(x.Rows))
		}
		p("];\n")
	case "ruby":
		p("# Generated by mmmbed; do not edit.\nQUERIES = {\n")
		for _, x := range queries {
			p("  %s => { name: %s, sql: %s, access: %s, rows: %s },\n", q(x.Name), q(x.Name), formattedSQLLiteral(lang, x.SQL, formatted, fmt.Sprintf("%s.unpack1('m0').force_encoding(Encoding::UTF_8)", encoded(x.SQL))), q(x.Access), q(x.Rows))
		}
		p("}.freeze\n")
	case "swift":
		p("// Generated by mmmbed; do not edit.\nimport Foundation\nstruct MmmbedQuery { let name: String; let sql: String; let access: String; let rows: String }\nlet queries: [String: MmmbedQuery] = [\n")
		for _, x := range queries {
			p("  %s: MmmbedQuery(name: %s, sql: %s, access: %s, rows: %s),\n", q(x.Name), q(x.Name), formattedSQLLiteral(lang, x.SQL, formatted, fmt.Sprintf("String(data: Data(base64Encoded: %s)!, encoding: .utf8)!", encoded(x.SQL))), q(x.Access), q(x.Rows))
		}
		p("]\n")
	case "kotlin":
		p("// Generated by mmmbed; do not edit.\ndata class MmmbedQuery(val name: String, val sql: String, val access: String, val rows: String)\nval queries: Map<String, MmmbedQuery> = mapOf(\n")
		for i, x := range queries {
			if i > 0 {
				p(",\n")
			}
			p("  %s to MmmbedQuery(%s, %s, %s, %s)", q(x.Name), q(x.Name), formattedSQLLiteral(lang, x.SQL, formatted, fmt.Sprintf("String(java.util.Base64.getDecoder().decode(%s), Charsets.UTF_8)", jvmEncoded(x.SQL, "kotlin"))), q(x.Access), q(x.Rows))
		}
		p("\n)\n")
	case "scala":
		p("// Generated by mmmbed; do not edit.\nfinal case class MmmbedQuery(name: String, sql: String, access: String, rows: String)\nobject MmmbedQueries {\n  val queries: Map[String, MmmbedQuery] = Map(\n")
		for i, x := range queries {
			if i > 0 {
				p(",\n")
			}
			p("    %s -> MmmbedQuery(%s, %s, %s, %s)", q(x.Name), q(x.Name), formattedSQLLiteral(lang, x.SQL, formatted, fmt.Sprintf("new String(java.util.Base64.getDecoder.decode(%s), java.nio.charset.StandardCharsets.UTF_8)", jvmEncoded(x.SQL, "scala"))), q(x.Access), q(x.Rows))
		}
		p("\n  )\n}\n")
	case "dart":
		p("// Generated by mmmbed; do not edit.\nimport 'dart:convert';\nfinal Map<String, Map<String, String>> queries = {\n")
		for _, x := range queries {
			p("  %s: {'name': %s, 'sql': %s, 'access': %s, 'rows': %s},\n", q(x.Name), q(x.Name), formattedSQLLiteral(lang, x.SQL, formatted, fmt.Sprintf("utf8.decode(base64.decode(%s))", encoded(x.SQL))), q(x.Access), q(x.Rows))
		}
		p("};\n")
	case "lua":
		p("-- Generated by mmmbed; do not edit.\nlocal queries = {\n")
		for _, x := range queries {
			p("  [%s] = {name = %s, sql = %s, access = %s, rows = %s},\n", luaString(x.Name), luaString(x.Name), formattedSQLLiteral(lang, x.SQL, formatted, luaString(x.SQL)), luaString(x.Access), luaString(x.Rows))
		}
		p("}\nreturn { queries = queries }\n")
	case "perl":
		p("# Generated by mmmbed; do not edit.\nuse utf8;\nuse MIME::Base64 qw(decode_base64);\nuse Encode qw(decode);\nour %%queries = (\n")
		for _, x := range queries {
			p("  %s => { name => %s, sql => %s, access => %s, rows => %s },\n", q(x.Name), q(x.Name), formattedSQLLiteral(lang, x.SQL, formatted, fmt.Sprintf("decode('UTF-8', decode_base64(%s))", encoded(x.SQL))), q(x.Access), q(x.Rows))
		}
		p(");\n1;\n")
	case "r":
		p("# Generated by mmmbed; do not edit.\nqueries <- list(\n")
		for i, x := range queries {
			if i > 0 {
				p(",\n")
			}
			p("  %s = list(name = %s, sql = %s, access = %s, rows = %s)", q(x.Name), q(x.Name), formattedSQLLiteral(lang, x.SQL, formatted, rString(x.SQL)), q(x.Access), q(x.Rows))
		}
		p("\n)\n")
	case "julia":
		p("# Generated by mmmbed; do not edit.\nusing Base64\nconst QUERIES = Dict(\n")
		for _, x := range queries {
			p("  %s => (name = %s, sql = %s, access = %s, rows = %s),\n", q(x.Name), q(x.Name), formattedSQLLiteral(lang, x.SQL, formatted, fmt.Sprintf("String(base64decode(%s))", encoded(x.SQL))), q(x.Access), q(x.Rows))
		}
		p(")\n")
	case "elixir":
		p("# Generated by mmmbed; do not edit.\ndefmodule MmmbedQueries do\n  def queries do\n    %%{\n")
		for _, x := range queries {
			p("      %s => %%{name: %s, sql: %s, access: %s, rows: %s},\n", q(x.Name), q(x.Name), formattedSQLLiteral(lang, x.SQL, formatted, fmt.Sprintf("Base.decode64!(%s)", encoded(x.SQL))), q(x.Access), q(x.Rows))
		}
		p("    }\n  end\nend\n")
	default:
		return fmt.Errorf("unsupported SQL output language %q", lang)
	}
	_, err := io.WriteString(w, b.String())
	return err
}

func rustString(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch r {
		case '\\':
			b.WriteString(`\\`)
		case '"':
			b.WriteString(`\"`)
		case '\n':
			b.WriteString(`\n`)
		case '\r':
			b.WriteString(`\r`)
		case '\t':
			b.WriteString(`\t`)
		default:
			if unicode.IsControl(r) {
				fmt.Fprintf(&b, `\u{%x}`, r)
			} else {
				b.WriteRune(r)
			}
		}
	}
	b.WriteByte('"')
	return b.String()
}

func luaString(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, c := range []byte(s) {
		if c == '"' || c == '\\' {
			b.WriteByte('\\')
			b.WriteByte(c)
		} else if c == '\n' {
			b.WriteString(`\n`)
		} else if c == '\r' {
			b.WriteString(`\r`)
		} else if c == '\t' {
			b.WriteString(`\t`)
		} else if c < 32 || c == 127 {
			fmt.Fprintf(&b, "\\%03d", c)
		} else {
			b.WriteByte(c)
		}
	}
	b.WriteByte('"')
	return b.String()
}

func rString(s string) string {
	var b strings.Builder
	b.WriteString("intToUtf8(c(")
	for i, r := range []rune(s) {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprintf(&b, "%d", r)
	}
	b.WriteString("))")
	return b.String()
}
