package sqlquery

import (
	"encoding/json"
	"fmt"
	"go/token"
	"io"
	"sort"
	"strconv"
	"strings"
	"unicode/utf8"
)

// Options controls source generation.
type Options struct {
	Prefix     string // C/C++ symbol prefix; defaults to mmmbed.
	GoPackage  string // Go package declaration; defaults to main.
	SingleLine bool   // Join safe SQL line breaks with spaces.
	Formatted  bool   // Render formatted SQL as readable multiline literals.
}

// RenderTo writes a source-language catalog. C and C++ catalogs own static,
// NUL-terminated SQL strings; other supported languages expose text strings.
func RenderTo(w io.Writer, language string, queries []Query, options Options) error {
	language = strings.ToLower(language)
	if options.Formatted && options.SingleLine {
		return fmt.Errorf("formatted and single-line SQL cannot be combined")
	}
	if options.SingleLine && language != "c" && language != "cpp" {
		return fmt.Errorf("single-line SQL is only supported for C and C++ output")
	}
	prefix := options.Prefix
	if prefix == "" {
		prefix = "mmmbed"
	}
	if !identifier.MatchString(prefix) {
		return fmt.Errorf("invalid prefix %q", prefix)
	}
	if len(queries) == 0 {
		return fmt.Errorf("no queries")
	}
	qs := append([]Query(nil), queries...)
	sort.Slice(qs, func(i, j int) bool { return qs[i].Name < qs[j].Name })
	names := map[string]bool{}
	for _, q := range qs {
		if !identifier.MatchString(q.Name) || ((language == "c" || language == "cpp") && q.Name == "COUNT") || names[q.Name] {
			return fmt.Errorf("invalid or duplicate query name %q", q.Name)
		}
		names[q.Name] = true
		if strings.TrimSpace(q.SQL) == "" || !utf8.ValidString(q.SQL) || strings.ContainsRune(q.SQL, 0) {
			return fmt.Errorf("invalid SQL for %s", q.Name)
		}
		if q.Access != "read" && q.Access != "write" {
			return fmt.Errorf("invalid access for %s", q.Name)
		}
		if q.Rows != "zero" && q.Rows != "zero-or-one" && q.Rows != "one" && q.Rows != "many" {
			return fmt.Errorf("invalid rows for %s", q.Name)
		}
	}
	if language != "c" && language != "cpp" {
		return renderOther(w, language, qs, options)
	}
	var b strings.Builder
	p := func(f string, a ...any) { fmt.Fprintf(&b, f, a...) }
	upper := strings.ToUpper(prefix)
	p("/* Generated by mmmbed; do not edit. */\n/* clang-format off */\n#pragma once\n#include <stddef.h>\n\nenum %s_access { %s_READ, %s_WRITE };\n", prefix, upper, upper)
	p("enum %s_rows { %s_ZERO, %s_ZERO_OR_ONE, %s_ONE, %s_MANY };\n", prefix, upper, upper, upper, upper)
	p("typedef enum %s_query_id {\n", prefix)
	for _, q := range qs {
		p("  %s_QUERY_%s,\n", upper, q.Name)
	}
	p("  %s_QUERY_COUNT\n} %s_query_id_t;\n", upper, prefix)
	p("struct %s_query { const char *name; const char *sql; enum %s_access access; enum %s_rows rows; };\n", prefix, prefix, prefix)
	p("static const struct %s_query %s_queries[] = {\n", prefix, prefix)
	for _, q := range qs {
		sql := q.SQL
		if options.SingleLine {
			var err error
			sql, err = singleLineSQL(sql)
			if err != nil {
				return fmt.Errorf("%s: %w", q.Name, err)
			}
		}
		chunkSize := 512
		if options.SingleLine {
			chunkSize = 4095
		}
		literal := cStringChunked(sql, chunkSize)
		if options.Formatted {
			literal = multilineSQLLiteral(language, sql)
		}
		p("  {%s, %s, %s_%s, %s_%s},\n", strconv.Quote(q.Name), literal, upper, strings.ToUpper(q.Access), upper, strings.ToUpper(strings.ReplaceAll(q.Rows, "-", "_")))
	}
	p("};\n/* clang-format on */\n")
	_, err := io.WriteString(w, b.String())
	return err
}

// singleLineSQL rejects cases where a line break may be significant to SQL.
func singleLineSQL(sql string) (string, error) {
	if strings.Contains(sql, "--") || strings.Contains(sql, "#") || strings.Contains(sql, "/*") {
		return "", fmt.Errorf("single-line SQL cannot contain comments")
	}
	lines := strings.Split(sql, "\n")
	lex := sqlLex{postgres: true, mysql: true}
	for i, line := range lines {
		lex.scan(line + "\n")
		if !lex.normal() {
			return "", fmt.Errorf("single-line SQL cannot contain multiline literals or identifiers")
		}
		if i+1 < len(lines) && strings.HasSuffix(strings.TrimSpace(line), "'") && strings.HasPrefix(strings.TrimSpace(lines[i+1]), "'") {
			return "", fmt.Errorf("single-line SQL cannot join continued string literals")
		}
		lines[i] = strings.TrimSpace(line)
	}
	return strings.Join(lines, " "), nil
}

func renderOther(w io.Writer, language string, qs []Query, options Options) error {
	var b strings.Builder
	p := func(f string, a ...any) { fmt.Fprintf(&b, f, a...) }
	quote := func(s string) string { v, _ := json.Marshal(s); return string(v) }
	switch language {
	case "go":
		pkg := options.GoPackage
		if pkg == "" {
			pkg = "main"
		}
		if !token.IsIdentifier(pkg) || pkg == "_" || token.Lookup(pkg).IsKeyword() {
			return fmt.Errorf("invalid Go package %q", pkg)
		}
		p("// Code generated by mmmbed; DO NOT EDIT.\npackage %s\n\n", pkg)
		p("// Query describes an embedded SQL statement. Access and Rows are declared metadata.\ntype Query struct { Name, SQL, Access, Rows string }\n\nvar Queries = map[string]Query{\n")
		for _, q := range qs {
			sql := strconv.Quote(q.SQL)
			if options.Formatted {
				sql = multilineSQLLiteral(language, q.SQL)
			}
			p("  %s: {%s, %s, %s, %s},\n", strconv.Quote(q.Name), strconv.Quote(q.Name), sql, strconv.Quote(q.Access), strconv.Quote(q.Rows))
		}
		p("}\n")
	case "python":
		p("# Generated by mmmbed; do not edit.\nqueries = {\n")
		for _, q := range qs {
			sql := quote(q.SQL)
			if options.Formatted {
				sql = multilineSQLLiteral(language, q.SQL)
			}
			p("    %s: {'name': %s, 'sql': %s, 'access': %s, 'rows': %s},\n", quote(q.Name), quote(q.Name), sql, quote(q.Access), quote(q.Rows))
		}
		p("}\n")
	case "javascript", "typescript":
		p("// Generated by mmmbed; do not edit.\n")
		if language == "typescript" {
			p("export interface Query { name: string; sql: string; access: 'read' | 'write'; rows: 'zero' | 'zero-or-one' | 'one' | 'many' }\nexport const queries: Record<string, Query> = {\n")
		} else {
			p("const queries = {\n")
		}
		for _, q := range qs {
			sql := quote(q.SQL)
			if options.Formatted {
				sql = multilineSQLLiteral(language, q.SQL)
			}
			p("  [%s]: {name: %s, sql: %s, access: %s, rows: %s},\n", quote(q.Name), quote(q.Name), sql, quote(q.Access), quote(q.Rows))
		}
		p("};\n")
		if language == "javascript" {
			p("module.exports = { queries };\n")
		}
	default:
		return renderExtended(w, language, qs, options.Formatted)
	}
	_, err := io.WriteString(w, b.String())
	return err
}

func cString(s string) string {
	return cStringChunked(s, 512)
}

func cStringChunked(s string, chunkSize int) string {
	var b strings.Builder
	b.WriteByte('"')
	for i, c := range []byte(s) {
		if i > 0 && i%chunkSize == 0 {
			b.WriteString("\"\n    \"")
		}
		if c == '"' || c == '\\' {
			b.WriteByte('\\')
			b.WriteByte(c)
		} else if c == '\n' {
			b.WriteString(`\n`)
		} else if c == '\r' {
			b.WriteString(`\r`)
		} else if c == '\t' {
			b.WriteString(`\t`)
		} else if c == '?' {
			b.WriteString(`\?`)
		} else if c >= 32 && c < 127 {
			b.WriteByte(c)
		} else {
			fmt.Fprintf(&b, "\\%03o", c)
		}
	}
	b.WriteByte('"')
	return b.String()
}
