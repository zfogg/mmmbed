func TestDuckDBIntegration(t *testing.T) {
	python, err := exec.LookPath("python")
	if err != nil {
		t.Skip("Python unavailable")
	}
	if err := exec.Command(python, "-c", "import duckdb").Run(); err != nil {
		t.Skip("DuckDB Python package unavailable")
	}
	qs, err := LoadPathsWithOptions([]string{"../examples/sql/duckdb"}, ParseOptions{Dialect: "duckdb"})
	if err != nil {
		t.Fatal(err)
	}
	var generated bytes.Buffer
	if err = RenderTo(&generated, "python", qs, Options{}); err != nil {
		t.Fatal(err)
	}
	dir := t.TempDir()
	if err = os.WriteFile(filepath.Join(dir, "queries.py"), generated.Bytes(), 0600); err != nil {
		t.Fatal(err)
	}
	program := `import duckdb
from queries import queries
db = duckdb.connect(':memory:')
db.execute('CREATE TABLE mmmbed_items (id INTEGER PRIMARY KEY, name VARCHAR)')
assert db.execute(queries['InsertItem']['sql'], {'id': 7, 'name': 'widget'}).fetchone() == (7,)
assert db.execute(queries['LookupItem']['sql'], [7]).fetchone() == ('widget',)
assert db.execute(queries['InspectLiterals']['sql']).fetchone() == ([']', 'a'], 'hello')
assert queries['InsertItem']['access'] == 'write' and queries['InsertItem']['rows'] == 'one'
`
	cmd := exec.Command(python, "-c", program)
	cmd.Dir = dir
	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("DuckDB integration: %v\n%s", err, out)
	}
}

func TestPostgresIntegration(t *testing.T) {
	dsn, container := os.Getenv("MMMBED_POSTGRES_DSN"), os.Getenv("MMMBED_POSTGRES_CONTAINER")
	if dsn == "" && container == "" {
		t.Skip("set MMMBED_POSTGRES_DSN or MMMBED_POSTGRES_CONTAINER to run PostgreSQL integration")
	}
	qs, err := LoadPathsWithOptions([]string{"../examples/sql/postgres"}, ParseOptions{Dialect: "postgres"})
	if err != nil {
		t.Fatal(err)
	}
	var generated bytes.Buffer
	if err = RenderTo(&generated, "python", qs, Options{}); err != nil {
		t.Fatal(err)
	}
	dir := t.TempDir()
	if err = os.WriteFile(filepath.Join(dir, "queries.py"), generated.Bytes(), 0600); err != nil {
		t.Fatal(err)
	}
	python := exec.Command("python", "-c", "import json; from queries import queries; print(json.dumps(queries))")
	python.Dir = dir
	out, err := python.Output()
	if err != nil {
		t.Fatalf("read generated catalog: %v", err)
	}
	var byName map[string]map[string]string
	if err = json.Unmarshal(out, &byName); err != nil {
		t.Fatal(err)
	}
	if byName["InsertItem"]["access"] != "write" || byName["LookupItem"]["rows"] != "zero-or-one" {
		t.Fatal("incorrect query metadata")
	}
	script := fmt.Sprintf("CREATE TEMP TABLE mmmbed_items (id INTEGER GENERATED ALWAYS AS IDENTITY, name TEXT);\nPREPARE insert_item(text) AS %s\nEXECUTE insert_item('widget');\nPREPARE lookup_item(integer) AS %s\nEXECUTE lookup_item(1);\nPREPARE inspect_literals AS %s\nEXECUTE inspect_literals;\n", byName["InsertItem"]["sql"], byName["LookupItem"]["sql"], byName["InspectLiterals"]["sql"])
	var cmd *exec.Cmd
	if container != "" {
		cmd = exec.Command("docker", "exec", "-i", container, "psql", "-U", "postgres", "-X", "-v", "ON_ERROR_STOP=1", "-At")
	} else {
		cmd = exec.Command("psql", dsn, "-X", "-v", "ON_ERROR_STOP=1", "-At")
	}
	cmd.Stdin = strings.NewReader(script)
	if out, err := cmd.CombinedOutput(); err != nil || !strings.Contains(string(out), "widget") || !strings.Contains(string(out), "hello") {
		t.Fatalf("PostgreSQL integration: %v\n%s", err, out)
	}
}
