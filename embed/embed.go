// Package embed renders binary assets as usable source code.
package embed

import (
	"bytes"
	"encoding/base64"
	"fmt"
	"go/token"
	"sort"
	"strconv"
	"strings"
	"unicode/utf8"
)

// Asset is an input file. Name is its basename, not its original path.
type Asset struct {
	Name string
	Data []byte
	// Parent is the immediate parent directory name, or empty for stdin.
	Parent string
}

// Languages lists the supported source languages.
func Languages() []string {
	return []string{"c", "cpp", "go", "javascript", "typescript", "python", "rust", "java", "csharp", "php", "ruby", "swift", "kotlin", "scala", "dart", "lua", "perl", "r", "julia", "elixir"}
}

// Options controls language-specific source generation.
type Options struct {
	// GoPackage is the package declaration for Go output. It defaults to main.
	GoPackage string
	// Variables optionally supplies one identifier per asset, in input order.
	Variables []string
	names     []string // precomputed by the streaming renderer
}

// Render generates a self-contained source file exposing a collection named assets.
func Render(language string, assets []Asset) ([]byte, error) {
	return RenderWithOptions(language, assets, Options{})
}

// RenderWithOptions generates source using the supplied language-specific options.
func RenderWithOptions(language string, assets []Asset, options Options) ([]byte, error) {
	if len(assets) == 0 {
		return nil, fmt.Errorf("%w: no assets", ErrInvalidInput)
	}
	seen := map[string]bool{}
	for _, a := range assets {
		if a.Name == "" || !utf8.ValidString(a.Name) || strings.ContainsAny(a.Name, "/\\\x00") {
			return nil, fmt.Errorf("%w: invalid filename %q", ErrInvalidInput, a.Name)
		}
		if !utf8.ValidString(a.Parent) || strings.ContainsAny(a.Parent, "/\\\x00") {
			return nil, fmt.Errorf("%w: invalid parent directory name %q", ErrInvalidInput, a.Parent)
		}
		if seen[a.Name] {
			return nil, fmt.Errorf("%w: duplicate filename %q", ErrInvalidInput, a.Name)
		}
		seen[a.Name] = true
	}
	lang := strings.ToLower(language)
	names := options.names
	var err error
	if names == nil {
		names, err = variableNames(lang, assets, options.Variables)
	}
	if err != nil {
		return nil, err
	}
	if lang == "r" {
		for _, n := range names {
			if n[0] == '_' {
				return nil, fmt.Errorf("%w: R variable name %q must start with a letter", ErrInvalidInput, n)
			}
		}
	}
	if lang == "elixir" {
		for _, n := range names {
			if n[0] < 'a' || n[0] > 'z' {
				return nil, fmt.Errorf("%w: Elixir variable name %q must start with a lowercase letter", ErrInvalidInput, n)
			}
		}
	}
	var b bytes.Buffer
	p := func(s string, a ...any) { fmt.Fprintf(&b, s, a...) }
	if lang == "c" || lang == "cpp" {
		return addAliases(lang, renderC(lang, assets), assets, names), nil
	}
	type pair struct{ n, d string }
	var entries []pair
	for _, a := range assets {
		entries = append(entries, pair{base64.StdEncoding.EncodeToString([]byte(a.Name)), base64.StdEncoding.EncodeToString(a.Data)})
	}
	switch lang {
	case "go":
		pkg := options.GoPackage
		if pkg == "" {
			pkg = "main"
		}
		if !token.IsIdentifier(pkg) || pkg == "_" {
			return nil, fmt.Errorf("%w: invalid Go package name %q", ErrInvalidInput, pkg)
		}
		p("// Code generated by mmmbed; DO NOT EDIT.\npackage %s\n\nimport \"encoding/base64\"\n\nfunc mmmbedDecode(s string) []byte { b, err := base64.StdEncoding.DecodeString(s); if err != nil { panic(err) }; return b }\n\nvar Assets = map[string][]byte{\n", pkg)
		for _, e := range entries {
			p("string(mmmbedDecode(%q)): mmmbedDecode(%q),\n", e.n, e.d)
		}
		p("}\n")
	case "javascript", "typescript":
		if lang == "typescript" {
			p("// Code generated by mmmbed. Requires Node.js.\nexport const assets: Record<string, Buffer> = {\n")
		} else {
			p("// Code generated by mmmbed. Requires Node.js.\nconst assets = {\n")
		}
		for _, e := range entries {
			p("[Buffer.from(%q, 'base64').toString('utf8')]: Buffer.from(%q, 'base64'),\n", e.n, e.d)
		}
		if lang == "typescript" {
			p("};\n")
		} else {
			p("};\nmodule.exports = { assets };\n")
		}
	case "python":
		p("# Code generated by mmmbed.\nimport base64\n\nassets = {\n")
		for _, e := range entries {
			p("base64.b64decode(%q).decode('utf-8'): base64.b64decode(%q),\n", e.n, e.d)
		}
		p("}\n")
	case "rust":
		// Literal byte arrays avoid external crates.
		p("// Code generated by mmmbed.\npub static ASSETS: &[(&str, &[u8])] = &[\n")
		for _, a := range assets {
			p("(%s, &[", rustString(a.Name))
			for _, v := range a.Data {
				p("%d,", v)
			}
			p("]),\n")
		}
		p("];\n")
	case "java":
		p("// Code generated by mmmbed.\nimport java.util.*;\nimport java.nio.charset.StandardCharsets;\nclass Mmmbed {\n  static final Map<String, byte[]> assets = new LinkedHashMap<>();\n  static {\n")
		for _, e := range entries {
			p("    assets.put(new String(Base64.getDecoder().decode(%s), StandardCharsets.UTF_8), Base64.getDecoder().decode(%s));\n", javaString(e.n), javaString(e.d))
		}
		p("  }\n}\n")
	case "csharp":
		p("// Code generated by mmmbed.\nusing System;\nusing System.Collections.Generic;\nusing System.Text;\npublic static class Mmmbed {\n public static readonly Dictionary<string, byte[]> Assets = new Dictionary<string, byte[]> {\n")
		for _, e := range entries {
			p("{ Encoding.UTF8.GetString(Convert.FromBase64String(%q)), Convert.FromBase64String(%q) },\n", e.n, e.d)
		}
		p("};\n}\n")
	case "php":
		p("<?php\n// Code generated by mmmbed.\n$assets = [\n")
		for _, e := range entries {
			p("base64_decode(%q) => base64_decode(%q),\n", e.n, e.d)
		}
		p("];\n")
	case "ruby":
		p("# Code generated by mmmbed.\nrequire 'base64'\nASSETS = {\n")
		for _, e := range entries {
			p("Base64.strict_decode64(%q).force_encoding('UTF-8') => Base64.strict_decode64(%q),\n", e.n, e.d)
		}
		p("}\n")
	case "swift":
		p("// Code generated by mmmbed.\nimport Foundation\nlet assets: [String: Data] = [\n")
		for _, e := range entries {
			p("String(data: Data(base64Encoded: %q)!, encoding: .utf8)!: Data(base64Encoded: %q)!,\n", e.n, e.d)
		}
		p("]\n")
	case "kotlin":
		p("// Code generated by mmmbed.\nimport java.util.Base64\nval assets: Map<String, ByteArray> = mapOf(\n")
		for _, e := range entries {
			p("String(Base64.getDecoder().decode(%q), Charsets.UTF_8) to Base64.getDecoder().decode(%q),\n", e.n, e.d)
		}
		p(")\n")
	case "scala":
		p("// Code generated by mmmbed.\nimport java.util.Base64\nimport java.nio.charset.StandardCharsets\nobject Mmmbed { val assets: Map[String, Array[Byte]] = Map(\n")
		for _, e := range entries {
			p("new String(Base64.getDecoder.decode(%q), StandardCharsets.UTF_8) -> Base64.getDecoder.decode(%q),\n", e.n, e.d)
		}
		p(") }\n")
	case "dart":
		p("// Code generated by mmmbed.\nimport 'dart:convert';\nimport 'dart:typed_data';\nfinal Map<String, Uint8List> assets = {\n")
		for _, e := range entries {
			p("utf8.decode(base64.decode(%q)): base64.decode(%q),\n", e.n, e.d)
		}
		p("};\n")
	case "lua":
		// Lua byte strings need no decoding library.
		p("-- Code generated by mmmbed.\nlocal assets = {\n")
		for _, a := range assets {
			p("[%s] = %s,\n", luaString([]byte(a.Name)), luaString(a.Data))
		}
		p("}\nreturn assets\n")
	case "perl":
		p("# Code generated by mmmbed.\nuse strict;\nuse warnings;\nuse MIME::Base64 qw(decode_base64);\nuse Encode qw(decode);\nour %%assets = (\n")
		for _, e := range entries {
			p("decode('UTF-8', decode_base64(%q)) => decode_base64(%q),\n", e.n, e.d)
		}
		p(");\n1;\n")
	case "r":
		// R's raw vectors do not require an optional package.
		p("# Code generated by mmmbed.\nassets <- list()\n")
		for _, a := range assets {
			p("assets[[rawToChar(as.raw(c(%s)))]] <- as.raw(c(%s))\n", numbers([]byte(a.Name)), numbers(a.Data))
		}
	case "julia":
		p("# Code generated by mmmbed.\nusing Base64\nconst assets = Dict{String, Vector{UInt8}}(\n")
		for _, e := range entries {
			p("String(base64decode(%q)) => base64decode(%q),\n", e.n, e.d)
		}
		p(")\n")
	case "elixir":
		p("# Code generated by mmmbed.\ndefmodule Mmmbed do\n  def assets do\n    %%{\n")
		for _, e := range entries {
			p("Base.decode64!(%q) => Base.decode64!(%q),\n", e.n, e.d)
		}
		p("    }\n  end\nend\n")
	default:
		return nil, fmt.Errorf("%w %q (supported: %s)", ErrUnsupportedLanguage, language, strings.Join(Languages(), ", "))
	}
	return addAliases(lang, b.Bytes(), assets, names), nil
}

func numbers(data []byte) string {
	v := make([]string, len(data))
	for i, x := range data {
		v[i] = strconv.Itoa(int(x))
	}
	return strings.Join(v, ",")
}
func luaString(data []byte) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, x := range data {
		fmt.Fprintf(&b, "\\%03d", x)
	}
	b.WriteByte('"')
	return b.String()
}
func renderC(lang string, assets []Asset) []byte {
	var b bytes.Buffer
	fmt.Fprintln(&b, "/* Code generated by mmmbed. */\n#include <stddef.h>\n\nstruct mmmbed_asset { const char *name; const unsigned char *data; size_t size; };")
	for i, a := range assets {
		fmt.Fprintf(&b, "static const unsigned char mmmbed_name_%d[] = {%s%s0};\n", i, numbers([]byte(a.Name)), comma(a.Name != ""))
		fmt.Fprintf(&b, "static const unsigned char mmmbed_data_%d[] = {%s%s0};\n", i, numbers(a.Data), comma(len(a.Data) > 0))
	}
	fmt.Fprintln(&b, "static const struct mmmbed_asset assets[] = {")
	for i, a := range assets {
		fmt.Fprintf(&b, "{(const char *)mmmbed_name_%d, mmmbed_data_%d, %d},\n", i, i, len(a.Data))
	}
	fmt.Fprintf(&b, "};\nstatic const size_t assets_count = %d;\n", len(assets))
	return b.Bytes()
}
func comma(ok bool) string {
	if ok {
		return ","
	}
	return ""
}

// SortedLanguages returns a sorted copy for display.
func SortedLanguages() []string { l := Languages(); sort.Strings(l); return l }

func rustString(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch r {
		case '\\':
			b.WriteString(`\\`)
		case '"':
			b.WriteString(`\"`)
		case '\n':
			b.WriteString(`\n`)
		case '\r':
			b.WriteString(`\r`)
		case '\t':
			b.WriteString(`\t`)
		default:
			if r < 32 || r == 127 {
				fmt.Fprintf(&b, `\u{%x}`, r)
			} else {
				b.WriteRune(r)
			}
		}
	}
	b.WriteByte('"')
	return b.String()
}

// Java class-file string constants are limited to 65535 bytes.
func javaString(s string) string {
	const chunk = 16000
	if len(s) <= chunk {
		return strconv.Quote(s)
	}
	var parts []string
	for len(s) > 0 {
		n := len(s)
		if n > chunk {
			n = chunk
		}
		parts = append(parts, strconv.Quote(s[:n]))
		s = s[n:]
	}
	return "String.join(\"\", " + strings.Join(parts, ", ") + ")"
}
